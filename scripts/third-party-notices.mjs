// Writes THIRD_PARTY_NOTICES.md from the dependency tree: the npm packages bundled into the apps
// (`pnpm licenses list --prod`) and every Rust crate the workspace depends on (`cargo metadata`),
// with its license expression as published. Run from the repository root: `pnpm notices`.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const run = (command, args) => execFileSync(command, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

/** The first copyright line of a package's license file, if it has one. */
function copyright(dir) {
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name));
  if (!file) return null;
  const line = readFileSync(join(dir, file), 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .find((l) => /^copyright\b/i.test(l) || /^\(c\)/i.test(l));
  return line ?? null;
}

const npm = JSON.parse(run('pnpm', ['licenses', 'list', '--prod', '--json', '-r']));
const npmRows = Object.entries(npm)
  .flatMap(([license, packages]) =>
    packages.map((p) => ({ name: p.name, version: p.versions.join(', '), license, copyright: p.paths.map(copyright).find(Boolean) ?? '' })),
  )
  .sort((a, b) => a.name.localeCompare(b.name));

const metadata = JSON.parse(run('cargo', ['metadata', '--format-version', '1', '--locked']));
const members = new Set(metadata.workspace_members);
const byLicense = new Map();
for (const crate of metadata.packages) {
  if (members.has(crate.id)) continue;
  const license = crate.license ?? (crate.license_file ? `see ${crate.license_file}` : 'unspecified');
  byLicense.set(license, [...(byLicense.get(license) ?? []), `${crate.name} ${crate.version}`]);
}
const rustGroups = [...byLicense].map(([license, crates]) => [license, crates.sort()]).sort(([a], [b]) => a.localeCompare(b));

const fontDir = 'apps/web/node_modules/@fontsource-variable/fredoka';
const ofl = existsSync(join(fontDir, 'LICENSE'))
  ? readFileSync(join(fontDir, 'LICENSE'), 'utf8').replace(/^Copyright[^\n]*\n+/i, '').trim()
  : '';

const escape = (text) => text.replaceAll('|', '\\|');
const out = [
  '# Third-Party Notices',
  '',
  'AnkyLock is licensed under the GNU Affero General Public License v3.0 or later (see [`LICENSE`](LICENSE)). It includes or depends on the software below, under its own licenses. This file is generated by `pnpm notices` (`scripts/third-party-notices.mjs`); do not edit it by hand.',
  '',
  '## Bundled with the web and desktop apps (npm)',
  '',
  '| Package | Version | License | Copyright |',
  '|---|---|---|---|',
  ...npmRows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${escape(r.copyright)} |`),
  '',
  '### Fonts',
  '',
  'Fredoka, Plus Jakarta Sans and JetBrains Mono are bundled as WOFF2 files (Fontsource variable builds) under the SIL Open Font License 1.1:',
  '',
  '- Copyright 2016 The Fredoka Project Authors (https://github.com/hafontia/Fredoka-One)',
  '- Copyright 2020 The Plus Jakarta Sans Project Authors (https://github.com/tokotype/PlusJakartaSans)',
  '- Copyright 2020 The JetBrains Mono Project Authors (https://github.com/JetBrains/JetBrainsMono)',
  '',
  '```text',
  ofl,
  '```',
  '',
  '## Rust crates (desktop host and relay)',
  '',
  'Grouped by license expression as each crate publishes it (`A OR B`: AnkyLock may use either); each crate ships its license text in its source package on crates.io.',
  '',
  ...rustGroups.flatMap(([license, crates]) => [`### ${license}`, '', crates.join(', '), '']),
];
writeFileSync('THIRD_PARTY_NOTICES.md', `${out.join('\n').trimEnd()}\n`);
console.log(`THIRD_PARTY_NOTICES.md: ${npmRows.length} npm packages, ${rustGroups.reduce((n, [, c]) => n + c.length, 0)} crates`);
